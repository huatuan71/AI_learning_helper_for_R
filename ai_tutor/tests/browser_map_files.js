async (page, baseUrl = 'http://127.0.0.1:8014') => {
  const checks=[], requests=[],errors=[];
  const check=(ok,name)=>{if(!ok)throw Error(name);checks.push(name);};
  const onRequest=r=>{if(r.method()==='POST')requests.push({url:r.url(),type:r.headers()['content-type'],body:r.postDataJSON()});};
  const onError=e=>errors.push(e.message);
  page.on('request',onRequest);page.on('pageerror',onError);
  const route=async view=>{await page.evaluate(v=>{location.hash='/'+v;},view);await page.waitForFunction(v=>document.querySelector('#main-nav a[aria-current="page"]')?.hash==='#/'+v,view);};
  const detail=async id=>{await page.locator('#map-search').fill(id);await page.locator('.scene-orb-label[data-id="'+id+'"]').click();await page.waitForFunction(id=>document.querySelector('#detail-title')?.textContent.startsWith(id) && document.querySelector('.detail-actions'),id);};
  const ready=async()=>page.waitForFunction(()=>!document.querySelector('#send').disabled);
  const upload=async(name,content)=>{await page.locator('#r-file').setInputFiles({name,mimeType:'text/plain',buffer:Buffer.isBuffer(content)?content:Buffer.from(content,'utf8')});};
  const feedback=async text=>page.waitForFunction(t=>document.querySelector('#file-feedback').textContent.includes(t),text);
  try {
    await page.context().grantPermissions(['clipboard-read','clipboard-write']);
    await page.setViewportSize({width:1440,height:1000});await page.emulateMedia({reducedMotion:'no-preference'});
    await page.goto(baseUrl+'/#/knowledge');await page.reload();
    await page.waitForFunction(()=>document.querySelectorAll('.knowledge-orb').length===43);
    check(await page.locator('.knowledge-orb').count()===43,'43 orbs loaded');
    await page.waitForFunction(()=>document.querySelectorAll('.scene-orb-label').length===43);
    check(await page.locator('#map-viewport').getAttribute('data-orb-count')==='43','43 Three.js knowledge objects');
    check(await page.locator('#map-viewport').getAttribute('data-connection-mode')==='focus-only','focus-only relationship display');
    check(await page.locator('#map-legend>span').count()===8,'eight unit colors');
    await detail('K06');
    for(const label of ['概念讲解','函数语法','参数说明','示例代码','易错点','内容来源','先修知识','相关知识']) {
      check((await page.locator('#detail-body').textContent()).includes(label),'detail '+label);
    }
    check(await page.locator('.scene-orb-label[data-id="K06"]').getAttribute('aria-pressed')==='true','selected knowledge label');
    const drawer=await page.locator('#map-detail').boundingBox();
    check(drawer.width>=1440*.4,'desktop full-height detail overlay');
    await page.screenshot({path:'output/playwright/v3-desktop-map-detail.png',fullPage:true});
    await page.locator('#detail-close').click();
    await page.locator('#map-unit-toggle').click();
    await page.getByRole('option',{name:'类型与缺失',exact:true}).click();
    check(await page.locator('#map-unit').inputValue()==='类型与缺失','custom unit filter');
    await page.locator('#map-reset').click();
    check(await page.locator('#map-unit').inputValue()==='','reset unit filter');
    await detail('K06');
    const count=await page.locator('.message').count();
    await page.getByRole('button',{name:'在AI问答中讲解',exact:true}).click();
    await page.waitForFunction(n=>document.querySelectorAll('.message').length===n+1,count);await ready();
    check(requests.at(-1).url.endsWith('/api/chat') && requests.at(-1).body.knowledge_id==='K06','map sends knowledge_id to chat');
    check(await page.locator('#sidebar,#catalog,#catalog-toggle').count()===0,'no sidebar in chat');
    await page.locator('#topic-clear').click();
    check(await page.locator('#topic-chip').isHidden(),'topic chip closes');
    await page.locator('#question').fill('factor中的levels有什么作用？');await page.locator('#send').click();await ready();
    check(requests.at(-1).body.knowledge_id===null && requests.at(-1).body.history.length===0,'closed topic starts fresh retrieval');
    await route('knowledge');await detail('K06');
    await page.getByRole('button',{name:'给我一道练习',exact:true}).click();await ready();
    check(requests.at(-1).body.knowledge_id==='K06' && requests.at(-1).body.question==='给我练习','map exercise uses existing rule');
    await route('review');
    check(await page.locator('#sidebar,#catalog,#catalog-toggle').count()===0,'no sidebar in review');
    await page.locator('#question').fill('为什么不能用x == NA判断缺失？');await page.locator('#code').fill('x <- c(1,NA,3)\nx[x == NA]');
    await page.locator('#send').click();await ready();
    check(requests.at(-1).url.endsWith('/api/review'),'manual review JSON');
    await page.locator('#code-clear').click();
    await upload('example.R','x <- c(1, NA, 3)\nx[x == NA]');await feedback('已在本地读取');
    check((await page.locator('#code').inputValue()).includes('x[x == NA]'),'valid uppercase R file fills code');
    check(await page.locator('#file-name').textContent()==='example.R' && (await page.locator('#file-size').textContent()).includes('B'),'file name and size');
    await page.locator('#send').click();await ready();
    check(requests.at(-1).type==='application/json' && requests.at(-1).body.code.includes('x[x == NA]') && !('file' in requests.at(-1).body),'file contents submitted through existing JSON API');
    check((await page.locator('.review-message').last().textContent()).includes('参考案例'),'reference case explicit');
    const original=await page.locator('#code').inputValue();
    await upload('replacement.r','print(2)');await page.locator('#replace-file-dialog').waitFor({state:'visible'});
    check(await page.locator('#code').inputValue()===original,'overwrite waits for confirmation');
    await page.locator('#replace-file-cancel').click();check(await page.locator('#code').inputValue()===original,'cancel preserves code');
    await upload('replacement.r','print(2)');await page.locator('#replace-file-confirm').click();await feedback('已在本地读取');
    check(await page.locator('#code').inputValue()==='print(2)','confirmed replacement');
    await page.locator('#code').fill('print(3)');await page.locator('#file-remove').click();
    check(await page.locator('#file-info').isHidden() && await page.locator('#code').inputValue()==='print(3)','remove preserves edited code');
    const reject=async(name,content,expected,label)=>{await upload(name,content);await feedback(expected);check(await page.locator('#code').inputValue()==='print(3)',label);};
    await reject('wrong.txt','print(1)','扩展名','reject non R file');
    await reject('empty.R','','为空','reject empty file');
    await reject('spaces.R','   \n','为空','reject whitespace only');
    await reject('huge.R','x'.repeat(102401),'100KB','reject over 100KB');
    await reject('binary.R',Buffer.from([0,1,2,3]),'二进制','reject binary');
    await reject('encoding.R',Buffer.from([0xff,0xfe,0x61]),'UTF-8','reject invalid UTF8');
    await page.evaluate(()=>{window.__originalText=File.prototype.text;File.prototype.text=()=>Promise.reject(new Error('simulated read failure'));});
    await reject('unreadable.R','x','读取失败','read failure preserves code');
    await page.evaluate(()=>{File.prototype.text=window.__originalText;delete window.__originalText;});
    await page.evaluate(()=>{window.__originalBuffer=File.prototype.arrayBuffer;File.prototype.arrayBuffer=()=>Promise.reject(new Error('read failed'));});
    await reject('read-fails.R','x','读取失败','buffer read failure preserves code');
    await page.evaluate(()=>{File.prototype.arrayBuffer=window.__originalBuffer;delete window.__originalBuffer;});
    await page.locator('#code-clear').click();
    const hostile='<img src=x onerror=window.__fileInjected=1>.R';
    await upload(hostile,'print(1)');await feedback('已在本地读取');
    check(await page.locator('#file-name').textContent()===hostile && await page.evaluate(()=>!document.querySelector('#file-name img') && !window.__fileInjected),'file name safe text');
    await page.locator('#code-clear').click();
    await upload('long.R','#'+ 'x'.repeat(10000));await feedback('超过10000字符');
    const requestCount=requests.length;await page.locator('#send').click();
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('超过10000'));
    check(requests.length===requestCount && (await page.locator('#code').inputValue()).length===10001,'over 10000 retained but submit blocked');
    await page.locator('#code-clear').click();
    await page.locator('#file-drop').evaluate(n=>{const dt=new DataTransfer();dt.items.add(new File(['print(4)'],'drop.R',{type:'text/plain'}));n.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:dt}));});
    await feedback('已在本地读取');check(await page.locator('#code').inputValue()==='print(4)','drag drop reads R file');
    await page.locator('#file-drop').evaluate(n=>{const e=new Event('drop',{bubbles:true,cancelable:true});Object.defineProperty(e,'dataTransfer',{value:{items:[{webkitGetAsEntry:()=>({isDirectory:true})}],files:[]}});n.dispatchEvent(e);});
    await feedback('不支持目录');check(await page.locator('#code').inputValue()==='print(4)','directory rejected');
    await page.locator('#code-clear').click();
    await page.evaluate(()=>{window.__read=File.prototype.text;File.prototype.text=function(){if(this.name==='slow.R')return new Promise(resolve=>{window.__finishSlow=()=>resolve('print(1)');});return window.__read.call(this);};});
    await upload('slow.R','print(1)');await upload('latest.R','print(2)');await feedback('已在本地读取');
    await page.evaluate(()=>{window.__finishSlow();File.prototype.text=window.__read;delete window.__read;delete window.__finishSlow;});
    check(await page.locator('#code').inputValue()==='print(2)' && await page.locator('#file-name').textContent()==='latest.R','latest file wins asynchronous read');
    await page.locator('#code-clear').click();await upload('review.R','x <- c(1,NA,3)\nx[x == NA]');await feedback('已在本地读取');
    await page.locator('#question').fill('为什么不能用x == NA判断缺失？');await page.locator('#send').click();await ready();
    await page.screenshot({path:'output/playwright/v3-desktop-review.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});await route('knowledge');await page.locator('#map-reset').click();
    check(await page.locator('.scene-orb-label').count()===43,'mobile 43 knowledge objects');
    await detail('K06');
    const sheet=await page.locator('#map-detail').boundingBox();
    check(Math.abs(sheet.y+sheet.height-844)<2 && sheet.width===390
      && await page.locator('#map-detail').getAttribute('role')==='dialog'
      && await page.locator('#map-detail').getAttribute('aria-modal')===null,'mobile non-modal bottom drawer');
    check((await page.locator('#detail-title').textContent()).startsWith('K06'),'mobile selected knowledge details');
    await page.screenshot({path:'output/playwright/v3-mobile-map-detail.png',fullPage:false});
    await page.locator('#detail-close').focus();await page.keyboard.press('Shift+Tab');
    check(await page.evaluate(()=>document.querySelector('.app-header').contains(document.activeElement)&&!document.querySelector('.app-header').inert),'bottom drawer allows header focus');
    await page.locator('#nav-toggle').click();check(await page.locator('#main-nav').isVisible(),'header navigation opens over bottom drawer');
    await page.locator('#main-nav a[href="#/chat"]').click();await page.waitForFunction(()=>!document.querySelector('#layout').hidden);
    check(await page.locator('#map-detail').isHidden()&&!await page.evaluate(()=>document.body.classList.contains('map-detail-sheet-open')),'header navigation closes knowledge detail');
    await route('knowledge');await detail('K06');
    await page.keyboard.press('Escape');check(await page.locator('#map-detail').isHidden(),'bottom drawer Escape');
    await route('review');
    const input=await page.locator('.composer-dock').boundingBox(),output=await page.locator('#conversation-scroll').boundingBox();
    check(output.y>=input.y+input.height-2,'mobile review vertical layout');
    const sendBox=await page.locator('#send').boundingBox(),errorBox=await page.locator('#error-message').boundingBox();
    check(sendBox.y>=errorBox.y+errorBox.height,'mobile send does not cover error input');
    await page.screenshot({path:'output/playwright/v3-mobile-file-review.png',fullPage:true});
    for(const view of ['home','knowledge','chat','review','history']){
      await route(view);check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390 width '+view);
    }
    check(requests.every(r=>/\/api\/(chat|review)$/.test(r.url)),'no upload endpoint used');
    check(errors.length===0,'no uncaught errors ' + JSON.stringify(errors));
    await route('home');return {passed:checks.length,checks,errors};
  } finally {page.off('request',onRequest);page.off('pageerror',onError);}
}
