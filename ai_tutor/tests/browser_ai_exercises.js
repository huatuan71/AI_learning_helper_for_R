const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
async function run(page,baseUrl,outputDir) {
  const checks=[];const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const check=(value,label)=>{assert.ok(value,label);checks.push(label);};
  const store=fn=>page.evaluate(async source=>{
    const {learningStore}=await import('/static/learning-store.js?v=learning-v1');
    return new Function('store','return ('+source+')(store)')(learningStore);
  },fn.toString());
  await page.goto(baseUrl+'/#/history/review/ai');
  await page.waitForFunction(()=>document.body.dataset.learningReady==='true');
  await page.locator('#ai-exercise-generate').waitFor();
  await store(store=>store.resetLearningData());
  await page.reload();await page.locator('#ai-exercise-generate').waitFor();
  await page.locator('.lc-ai-knowledge input[value="K06"]').check();
  const scope = page.getByRole('combobox', {name:'选题范围', exact:true});
  await scope.click();
  check(await page.getByRole('listbox', {name:'选题范围', exact:true}).isVisible(), 'scope opens a styled listbox');
  await page.keyboard.press('End');
  await page.keyboard.press('Enter');
  check(await scope.textContent() === '综合练习', 'scope supports keyboard selection');
  await scope.click();
  await page.keyboard.press('Escape');
  check(await scope.evaluate(node => node === document.activeElement && node.getAttribute('aria-expanded') === 'false'), 'Escape closes listbox and restores focus');
  await scope.click();
  await page.getByRole('option', {name:'选择知识点', exact:true}).click();
  const search = page.getByRole('searchbox', {name:'搜索知识点或编号'});
  await search.fill('K06');
  check(await page.locator('.lc-ai-knowledge-option:visible').count() === 1, 'knowledge search filters by ID');
  await search.fill('没有这个知识点');
  check(await page.locator('.lc-ai-picker-empty').isVisible(), 'empty search displays feedback');
  await search.fill('');
  await page.locator('.lc-ai-knowledge input[value="K07"]').check();
  await page.locator('.lc-ai-knowledge input[value="K08"]').check();
  check(await page.locator('.lc-ai-knowledge input[value="K09"]').isDisabled(), 'three selections disable additional choices');
  await page.getByRole('button', {name:/移除 K07/}).click();
  check(!await page.locator('.lc-ai-knowledge input[value="K09"]').isDisabled(), 'removing a chip enables more choices');
  await page.locator('.lc-ai-knowledge input[value="K08"]').uncheck();
  await page.locator('#ai-exercise-generate').click();
  await page.locator('#model-dialog').waitFor({state:'visible'});
  check(true,'unconfigured generation opens model settings');
  await page.locator('#model-close').click();
  const response=await page.context().request.put(baseUrl+'/api/ai/config',{data:{mode:'ai',provider:'deepseek',model:'deepseek-chat',api_key:'browser-exercise-key',max_output_tokens:8192}});
  check(response.ok(),'mock upstream model configured');
  await page.reload();await page.locator('#ai-exercise-generate').waitFor();
  await page.locator('.lc-ai-settings>summary').click();
  await page.getByRole('combobox',{name:'题目数量',exact:true}).click();
  await page.getByRole('option',{name:'4题',exact:true}).click();
  const request=page.waitForRequest(request=>request.url().endsWith('/api/learning/exercises'));
  const generated=page.waitForResponse(response=>response.url().endsWith('/api/learning/exercises'));
  await page.locator('#ai-exercise-generate').click();
  const input=(await request).postDataJSON();
  const validResponse=await (await generated).json();
  check(input.knowledge_ids.join(',')==='K06'&&input.count===4,'actual request uses selected knowledge and count');
  await page.waitForFunction(()=>document.querySelectorAll('.lc-ai-question').length===4);
  check(await page.locator('.lc-ai-badge').count()===4,'all four formats carry AI labels');
  check(new Set((await store(store=>store.listAIExercises())).map(row=>row.format)).size===4,'generated batch covers all four requested formats');
  const choiceId = validResponse.questions.find(question => question.format === 'choice').id;
  const first = page.locator('.lc-ai-question').filter({has:page.locator(`input[name="${choiceId}"]`)});
  await first.locator('input[type=radio]').first().check();
  await first.locator('textarea').fill('我的推理 <script>window.bad=true</script>');
  await first.getByRole('button',{name:'解题提示',exact:true}).click();
  await first.locator('.lc-ai-hint').waitFor();
  await first.getByRole('button',{name:'锁定答案',exact:true}).click();
  await first.getByRole('combobox',{name:'自评',exact:true}).waitFor();
  check(await first.locator('textarea').isDisabled(),'locked answer becomes read-only');
  await page.reload();await first.getByRole('combobox',{name:'自评',exact:true}).waitFor();
  check(await first.locator('textarea').inputValue()==='我的推理 <script>window.bad=true</script>','refresh restores locked answer safely');
  await first.getByRole('button',{name:'参考答案',exact:true}).click();
  await first.locator('.lc-ai-reference').waitFor();
  await first.getByRole('combobox',{name:'自评',exact:true}).click();
  await page.getByRole('option',{name:'辅助完成',exact:true}).click();
  await page.evaluate(()=>{
    const put=IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put=function(...args){if(this.name==='aiExerciseAttempts'){IDBObjectStore.prototype.put=put;throw Error('模拟保存失败，请重试');}return put.apply(this,args);};
  });
  await first.getByRole('button',{name:'保存作答',exact:true}).click();
  await page.waitForFunction(()=>document.getElementById('ai-exercise-status').textContent.length>0);
  const retryId=(await store(store=>store.listAIExercises())).find(question => question.id === choiceId).draft.attemptId;
  await first.getByRole('button',{name:'保存作答',exact:true}).click();
  await first.getByRole('button',{name:'重新作答',exact:true}).waitFor();
  check((await store(store=>store.listAIExerciseAttempts()))[0].id===retryId,'save failure retry keeps stable attempt ID');
  const snapshot=await store(store=>store.snapshot());
  check(snapshot.aiExerciseAttempts.length===1&&snapshot.attempts.length===0,'AI attempt is separate from course scheduling');
  check(snapshot.aiExerciseAttempts[0].hintUsed,'hint assistance survives save');
  check(!await page.evaluate(()=>window.bad),'answer renders as safe text');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>{document.activeElement?.blur();scrollTo(0,0);});
  await page.screenshot({path:path.join(outputDir,'ai-exercise-desktop.png'),fullPage:true});
  await scope.click();
  const menu = page.getByRole('listbox', {name:'选题范围', exact:true});
  check(await menu.evaluate(node => getComputedStyle(node).backdropFilter.includes('blur')), 'scope menu uses the shared glass material');
  await page.screenshot({path:path.join(outputDir,'ai-exercise-scope-desktop.png')});
  await page.getByRole('heading', {name:'学习记录', exact:true}).click();
  check(await menu.isHidden(), 'clicking outside closes the scope menu');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(outputDir,'ai-exercise-mobile.png'),fullPage:true});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390px layout fits viewport');
  await scope.click();
  const bounds = await menu.boundingBox();
  check(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844, 'mobile scope menu fits viewport');
  await page.screenshot({path:path.join(outputDir,'ai-exercise-scope-mobile.png')});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:1000});
  const exported=page.waitForEvent('download');
  await first.getByRole('button',{name:'导出练习',exact:true}).click();
  check((await exported).suggestedFilename()==='r-tutor-ai-exercise.txt','text export uses safe stable filename');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.getByRole('button',{name:'复制代码',exact:true}).first().click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).length>0,'copy code writes actual code');
  await first.locator('details>summary').click();
  await first.locator('details button').first().click();
  await page.locator('#detail-title').waitFor({state:'visible'});
  check((await page.locator('#detail-title').textContent()).includes('K06'),'source navigates to actual course knowledge');
  await page.locator('#detail-body').getByRole('button',{name:'AI出题',exact:true}).click();
  await page.locator('#ai-exercise-generate').waitFor();
  check(await page.locator('.lc-ai-knowledge input[value="K06"]').isChecked(),'knowledge detail carries selected knowledge into same practice entry');
  const countBefore=(await store(store=>store.snapshot())).aiExercises.length;
  let release;let started;
  const waiting=new Promise(resolve=>{started=resolve;});
  const delay=async route=>{started();await new Promise(resolve=>{release=resolve;});await route.fulfill({json:validResponse}).catch(()=>{});};
  await page.route('**/api/learning/exercises',delay);
  await page.locator('#ai-exercise-generate').click();await waiting;
  await page.locator('#ai-exercise-cancel').click();release();
  await page.waitForTimeout(150);
  check((await store(store=>store.snapshot())).aiExercises.length===countBefore,'cancelled late response preserves saved question batch');
  await page.unroute('**/api/learning/exercises',delay);
  const expired=route=>route.fulfill({status:401,json:{error:{code:'SESSION_EXPIRED',message:'模型配置已过期'}}});
  await page.route('**/api/learning/exercises',expired);
  await page.locator('#ai-exercise-generate').click();
  await page.locator('#ai-exercise-configure').waitFor({state:'visible'});
  check((await store(store=>store.snapshot())).aiExercises.length===countBefore,'expired session retains previous questions');
  await page.unroute('**/api/learning/exercises',expired);
  await page.evaluate(()=>{location.hash='/history/summary';});
  await page.locator('#ai-summary-generate').waitFor();
  await page.waitForFunction(()=>!document.getElementById('ai-summary-generate').disabled);
  await page.locator('#ai-summary-generate').click();
  await page.locator('#learning-ai-summary').getByRole('button',{name:'练习',exact:true}).first().waitFor();
  await page.locator('#learning-ai-summary').getByRole('button',{name:'练习',exact:true}).first().click();
  await page.locator('#ai-exercise-generate').waitFor();
  check(await page.locator('.lc-ai-knowledge input[value="K06"]').isChecked(),'summary recommendation opens same selected knowledge range');
  await page.evaluate(async()=>{const {downloadOffline}=await import('/static/offline.js?v=learning-v1');await downloadOffline();});
  await page.context().setOffline(true);
  await page.reload();await page.locator('.lc-ai-question').first().waitFor();
  check(await page.locator('.lc-ai-question').count()===4,'offline refresh restores saved questions with complete PWA modules');
  await first.getByRole('button',{name:'重新作答',exact:true}).click();
  await first.getByRole('button',{name:'锁定答案',exact:true}).waitFor();
  check(!await first.locator('textarea').isDisabled(),'offline restart creates editable attempt');
  await page.context().setOffline(false);
  await first.getByRole('button',{name:'删除练习',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.lc-ai-question').length===3);
  check((await store(store=>store.snapshot())).aiExerciseAttempts.length===0,'delete removes associated attempts');
  assert.deepEqual(errors,[],'no browser errors');
  return {passed:checks.length,checks,errors};
}
async function main() {
  const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
  const outputDir=process.env.EXERCISE_TEST_OUTPUT||path.resolve(__dirname,'../output/playwright');
  fs.mkdirSync(outputDir,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'Asia/Shanghai',reducedMotion:'reduce'});
  const page=await context.newPage();
  try {
    const result=await run(page,process.env.BASE_URL||'http://127.0.0.1:8001',outputDir);
    result.browser=browser.version();console.log(JSON.stringify(result,null,2));
    fs.writeFileSync(path.join(outputDir,'ai-exercise-results.json'),JSON.stringify(result,null,2));
  } catch(error) {
    await page.screenshot({path:path.join(outputDir,'ai-exercise-failure.png'),fullPage:true});console.error(error);process.exitCode=1;
  } finally {await browser.close();}
}
if(require.main===module)main();
module.exports={run};
