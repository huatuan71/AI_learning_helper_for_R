import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const directory = new URL('../static/vendor/prism/', import.meta.url);
const core = readFileSync(new URL('prism-core.upstream.js', directory), 'utf8');
const grammar = readFileSync(new URL('prism-r.upstream.js', directory), 'utf8');
// Isolate upstream's browser/CommonJS detection and configure manual mode before execution.
const output = `// Generated by scripts/build_prism.mjs from PrismJS 1.30.0 (MIT).
const Prism = (function(window, WorkerGlobalScope, self, module, global) {
${core}
${grammar}
return Prism;
})({Prism:{manual:true, disableWorkerMessageHandler:true}});
export default Prism;
`;
writeFileSync(fileURLToPath(new URL('prism.js', directory)), output);
