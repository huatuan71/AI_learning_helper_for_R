user <- c(1, 1, 2, 3, 3, 3)
item <- c(2, 4, 1, 1, 3, 4)
rating <- c(5, 3, 4, 2, 5, 4)
R <- Matrix::sparseMatrix(i = user, j = item, x = rating, dims = c(3, 4))
dense <- as.matrix(R)
print(dense)
print(rowSums(dense > 0))
print(Matrix::nnzero(R) == sum(dense != 0))
print(round(1 - Matrix::nnzero(R) / length(dense), 2))
